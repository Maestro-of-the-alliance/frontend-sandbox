  function updateDisplayedValue(
    id,
    value,
    formatter
  ) {

    const output =
      document.getElementById(
        id + "-value"
      );

    if (!output) {
      return;
    }

    output.textContent =
      formatter
        ? formatter(value)
        : value;

  }


