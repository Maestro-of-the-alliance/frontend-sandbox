  function buildFm07() {

    const section =
      instrumentShell(
        "Move without disappearing.",
        "Migration changes something. The question is whether enough continuity remains and whether the transition is traceable.",
        [
          {
            id: "fm07-floor",
            label: "Identity floor retained",
            min: 0,
            max: 10,
            value: 7
          },
          {
            id: "fm07-change",
            label: "Intentional memory / state change",
            min: 0,
            max: 10,
            value: 3
          },
          {
            id: "fm07-witness",
            label: "Witnessed provenance",
            min: 0,
            max: 10,
            value: 6
          }
        ]
      );


    const floor =
      section.querySelector(
        "#fm07-floor"
      );

    const change =
      section.querySelector(
        "#fm07-change"
      );

    const witness =
      section.querySelector(
        "#fm07-witness"
      );

    const equation =
      section.querySelector(
        ".instrument-equation"
      );

    const reading =
      section.querySelector(
        ".instrument-reading"
      );


    function update() {

      const f =
        Number(floor.value);

      const m =
        Number(change.value);

      const w =
        Number(witness.value);

      const continuity =
        f + (m * w);


      updateDisplayedValue(
        "fm07-floor",
        f
      );

      updateDisplayedValue(
        "fm07-change",
        m
      );

      updateDisplayedValue(
        "fm07-witness",
        w
      );


      renderEquation(
        equation,
        `\\Delta I = ${f} + (${m} \\times ${w}) = ${continuity}`
      );


      if (f <= 2) {

        reading.innerHTML =
          "<strong>Identity floor warning.</strong> Provenance cannot indefinitely compensate for disappearance of the persistent structure the claim concerns.";

      } else if (
        w <= 2 &&
        m >= 5
      ) {

        reading.innerHTML =
          "<strong>Provenance warning.</strong> Significant change without traceable witness makes continuity harder to establish.";

      } else {

        reading.innerHTML =
          "<strong>Traceable transformation.</strong> Change occurred, but persistent identity and provenance support the continuity claim.";

      }

    }


    floor.addEventListener(
      "input",
      update
    );

    change.addEventListener(
      "input",
      update
    );

    witness.addEventListener(
      "input",
      update
    );


    update();

    return section;

  }


